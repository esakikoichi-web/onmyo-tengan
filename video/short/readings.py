# 読み（ナレーション）の統一辞書。edge-tts版・VOICEVOX版の両方から使う。
# 固有名詞・難読・誤読しやすい語を手動でかな化（pykakasiより優先）→残りをpykakasiでかな化。
# 新しい語で読みがおかしい時は R に1行足すだけでよい。読みの出典は高島易断の資料に準拠。
import pykakasi
R=[("青龍孔一","せいりゅうこういち"),("高島嘉右衛門","たかしまかえもん"),("嘉右衛門","かえもん"),
   ("若宮","わかみや"),("鍼医","しんい"),("宮人","きゅうじん"),("寵せらる","ちょうせらる"),("宮の字","みやのじ"),
   ("穿つ","うがつ"),("以て","もって"),("一卦","いっか"),("一言","ひとこと"),("一手","いって"),
   ("魚","うお"),  # 剥・六五「魚を貫く」の公式読み（高島易断資料に準拠。さかな→うお）
   ("匙","さじ"),("易","えき"),("観ます","みます"),("LINE","ライン")]
_k=pykakasi.kakasi()
def fix(t):
    for a,b in R: t=t.replace(a,b)
    # 残った漢字をすべてひらがなへ（自動読みに任せず原文どおりに読ませる）
    return ''.join(x['hira'] for x in _k.convert(t))
